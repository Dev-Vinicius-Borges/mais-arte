create table if not exists public.endereco (
  id_endereco bigint generated by default as identity primary key,
  chave_normalizada text not null unique,
  cep varchar(8),
  logradouro text not null check (btrim(logradouro) <> ''),
  numero varchar(30),
  complemento text,
  bairro text,
  cidade text,
  uf char(2),
  ponto_referencia text,
  criado_em timestamptz not null default now(),
  constraint ck_endereco_cep check (cep is null or cep ~ '^[0-9]{8}$'),
  constraint ck_endereco_uf check (uf is null or uf ~ '^[A-Z]{2}$')
);

alter table public.evento
  add column if not exists fk_id_endereco bigint
  references public.endereco(id_endereco);

insert into public.endereco (chave_normalizada, logradouro)
select distinct lower(regexp_replace(btrim(espaco.endereco), '\s+', ' ', 'g')),
       btrim(espaco.endereco)
from public.evento evento
join public.espaco_cultural espaco
  on espaco.id_espaco_cultural = evento.fk_id_espaco_cultural
where evento.fk_id_endereco is null
  and espaco.endereco is not null
  and btrim(espaco.endereco) <> ''
on conflict (chave_normalizada) do nothing;

update public.evento evento
set fk_id_endereco = endereco.id_endereco
from public.espaco_cultural espaco,
     public.endereco endereco
where evento.fk_id_endereco is null
  and espaco.id_espaco_cultural = evento.fk_id_espaco_cultural
  and endereco.chave_normalizada =
      lower(regexp_replace(btrim(espaco.endereco), '\s+', ' ', 'g'));

do $$
begin
  if exists (select 1 from public.evento where fk_id_endereco is null) then
    raise exception 'Informe o endereço dos eventos que não possuem endereço no espaço associado antes de aplicar esta migration.';
  end if;
end
$$;

alter table public.evento
  alter column fk_id_endereco set not null;

create table if not exists public.evento_espaco_cultural (
  id_evento bigint not null references public.evento(id_evento) on delete cascade,
  id_espaco_cultural bigint not null references public.espaco_cultural(id_espaco_cultural) on delete cascade,
  primary key (id_evento, id_espaco_cultural)
);

insert into public.evento_espaco_cultural (id_evento, id_espaco_cultural)
select id_evento, fk_id_espaco_cultural
from public.evento
on conflict do nothing;

alter table public.evento
  drop column fk_id_espaco_cultural;

alter table public.endereco enable row level security;
alter table public.evento_espaco_cultural enable row level security;

create policy "enderecos podem ser lidos publicamente"
  on public.endereco for select
  using (
    exists (
      select 1 from public.evento evento
      where evento.fk_id_endereco = endereco.id_endereco
        and evento.ativo = true
    )
  );

create policy "vinculos de eventos ativos podem ser lidos publicamente"
  on public.evento_espaco_cultural for select
  using (
    exists (
      select 1 from public.evento evento
      where evento.id_evento = evento_espaco_cultural.id_evento
        and evento.ativo = true
    )
  );

create index if not exists idx_evento_endereco on public.evento (fk_id_endereco);
create index if not exists idx_evento_espaco_cultural_espaco
  on public.evento_espaco_cultural (id_espaco_cultural);
