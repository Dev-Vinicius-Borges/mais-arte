do $$
begin
  if exists (select 1 from public.perfil_artista limit 1)
    or exists (select 1 from public.banda limit 1)
    or exists (select 1 from public.evento limit 1)
    or exists (select 1 from public.espaco_cultural limit 1) then
    raise exception 'A recriação do schema foi interrompida porque uma ou mais tabelas contêm dados.';
  end if;
end
$$;

drop table if exists public.evento_espaco_cultural;
drop table if exists public.evento;
drop table if exists public.endereco;
drop table if exists public.espaco_cultural;
drop table if exists public.banda;
drop table if exists public.perfil_artista;

create table public.perfil_artista (
  id_perfil_artista bigint generated by default as identity primary key,
  nome_artistico varchar(150),
  bio_profissional text,
  foto_principal varchar(255),
  data_inicio_atividade date,
  reputacao_score double precision not null default 0,
  verificado boolean not null default false,
  ativo boolean not null default true,
  generos_musicais jsonb not null default '[]'::jsonb
);

create table public.banda (
  id_banda bigint generated by default as identity primary key,
  nome_banda varchar(150) not null,
  descricao text not null,
  data_formacao date not null,
  foto_principal varchar(255),
  reputacao_score double precision not null default 0,
  verificado boolean not null default false,
  ativo boolean not null default true,
  generos_musicais jsonb not null default '[]'::jsonb
);

create table public.espaco_cultural (
  id_espaco_cultural bigint generated by default as identity primary key,
  nome_espaco varchar(150) not null,
  descricao text not null,
  site varchar(255),
  horario_funcionamento jsonb not null default '{}'::jsonb,
  capacidade_maxima integer,
  publico boolean not null default true,
  endereco text,
  foto_principal varchar(255),
  reputacao_score double precision not null default 0,
  verificado boolean not null default false,
  ativo boolean not null default true
);

create table public.evento (
  id_evento bigint generated by default as identity primary key,
  nome_evento varchar(150) not null,
  descricao text not null,
  data_evento date not null,
  hora_inicio time not null,
  hora_fim time,
  url_cartaz varchar(255),
  link_ingresso varchar(255),
  preco_ingresso numeric(10, 2) not null default 0,
  endereco text not null check (btrim(endereco) <> ''),
  foto_principal varchar(255),
  reputacao_score double precision not null default 0,
  verificado boolean not null default false,
  ativo boolean not null default true
);

create table public.evento_espaco_cultural (
  id_evento bigint not null references public.evento(id_evento) on delete cascade,
  id_espaco_cultural bigint not null references public.espaco_cultural(id_espaco_cultural) on delete cascade,
  primary key (id_evento, id_espaco_cultural)
);

create index idx_evento_data_ativo
  on public.evento (data_evento, ativo);
create index idx_artista_ativo_verificado
  on public.perfil_artista (ativo, verificado);
create index idx_espaco_ativo_verificado
  on public.espaco_cultural (ativo, verificado);
create index idx_banda_nome
  on public.banda using gin (to_tsvector('simple', nome_banda));
create index idx_evento_espaco_cultural_espaco
  on public.evento_espaco_cultural (id_espaco_cultural);

alter table public.perfil_artista enable row level security;
alter table public.banda enable row level security;
alter table public.espaco_cultural enable row level security;
alter table public.evento enable row level security;
alter table public.evento_espaco_cultural enable row level security;

create policy "conteudo ativo pode ser lido publicamente"
  on public.perfil_artista for select
  using (ativo = true and verificado = true);

create policy "bandas ativas podem ser lidas publicamente"
  on public.banda for select
  using (ativo = true);

create policy "espacos ativos podem ser lidos publicamente"
  on public.espaco_cultural for select
  using (ativo = true and verificado = true);

create policy "eventos ativos podem ser lidos publicamente"
  on public.evento for select
  using (ativo = true);

create policy "vinculos de conteudo ativo podem ser lidos publicamente"
  on public.evento_espaco_cultural for select
  using (
    exists (
      select 1
      from public.evento evento
      where evento.id_evento = evento_espaco_cultural.id_evento
        and evento.ativo = true
    )
    and exists (
      select 1
      from public.espaco_cultural espaco
      where espaco.id_espaco_cultural = evento_espaco_cultural.id_espaco_cultural
        and espaco.ativo = true
        and espaco.verificado = true
    )
  );
